/** جميع الرسائل اليومية (365 رسالة فريدة). */
export function getAllDailyMessages(): string[] {
  if (customDailyMessages.length > 0) return customDailyMessages;
  const all: string[] = [];
  for (let o = 0; o < dailyOpenings.length; o++) {
    for (let b = 0; b < dailyBodies.length; b++) {
      // نزيح ترتيب الرسائل مع كل افتتاحية حتى لا تتكرر الرسالة نفسها بعد 73 يومًا مباشرة
      const body = dailyBodies[(b + o * 17) % dailyBodies.length];
      all.push(`${dailyOpenings[o]} ${body}`);
    }
  }
  return all;
}
